-- PLANTILLA DE ESQUEMA PARA SUPABASE (NO CONECTADA AL PROTOTIPO LOCAL)
-- Revise y pruebe en un proyecto de desarrollo antes de usar en producción.
-- La autenticación se delega a Supabase Auth: nunca almacene contraseñas aquí.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  phone text,
  role text not null default 'pasajero' check (role in ('pasajero','admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.routes (
  id bigint generated by default as identity primary key,
  company text not null,
  origin text not null,
  destination text not null,
  departure_time time not null,
  arrival_time time,
  travel_minutes integer,
  fare_cop integer not null check (fare_cop >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (origin <> destination)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id),
  route_id bigint not null references public.routes(id),
  travel_date date not null,
  passenger_count integer not null check (passenger_count between 1 and 8),
  total_cop integer not null check (total_cop >= 0),
  status text not null default 'pending' check (status in ('pending','confirmed','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.dispatches (
  id uuid primary key default gen_random_uuid(),
  route_id bigint references public.routes(id),
  company text not null,
  origin text not null,
  destination text not null,
  departure_date date not null,
  departure_time time not null,
  bay text not null,
  driver_name text,
  vehicle_plate text,
  status text not null default 'scheduled'
    check (status in ('scheduled','boarding','on_time','delayed','completed','cancelled')),
  created_at timestamptz not null default now(),
  check (origin <> destination)
);

create table if not exists public.incidents (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid references public.profiles(id),
  category text not null,
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  location text,
  description text not null,
  status text not null default 'pending' check (status in ('pending','review','closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id),
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);

create index if not exists bookings_profile_date_idx on public.bookings(profile_id, travel_date);
create index if not exists dispatches_date_time_idx on public.dispatches(departure_date, departure_time);
create index if not exists incidents_status_idx on public.incidents(status);

alter table public.profiles enable row level security;
alter table public.routes enable row level security;
alter table public.bookings enable row level security;
alter table public.dispatches enable row level security;
alter table public.incidents enable row level security;
alter table public.audit_logs enable row level security;

-- Perfiles: cada pasajero consulta su perfil; el administrador puede consultar todos.
create policy "profiles_select_own_or_admin" on public.profiles
for select to authenticated
using (auth.uid() = id or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));

create policy "profiles_update_own_or_admin" on public.profiles
for update to authenticated
using (auth.uid() = id or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
))
with check (auth.uid() = id or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));

-- Rutas: lectura para usuarios autenticados; escritura solo para administrador.
create policy "routes_read_authenticated" on public.routes
for select to authenticated using (active or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));
create policy "routes_admin_manage" on public.routes
for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active));

-- Reservas: pasajero solo ve y crea las propias; administración ve y gestiona todas.
create policy "bookings_read_own_or_admin" on public.bookings
for select to authenticated using (profile_id = auth.uid() or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));
create policy "bookings_insert_own" on public.bookings
for insert to authenticated with check (profile_id = auth.uid());
create policy "bookings_admin_update" on public.bookings
for update to authenticated using (exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
)) with check (exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));

-- Despachos: lectura autenticada; administración gestiona.
create policy "dispatches_read_authenticated" on public.dispatches
for select to authenticated using (true);
create policy "dispatches_admin_manage" on public.dispatches
for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active));

-- Incidencias: pasajeros crean y consultan propias; administración consulta y actualiza todas.
create policy "incidents_read_own_or_admin" on public.incidents
for select to authenticated using (reporter_id = auth.uid() or exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));
create policy "incidents_insert_own" on public.incidents
for insert to authenticated with check (reporter_id = auth.uid());
create policy "incidents_admin_update" on public.incidents
for update to authenticated using (exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
)) with check (exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));

-- Auditoría: solo administrador puede leer; inserts se recomiendan desde funciones backend confiables.
create policy "audit_admin_read" on public.audit_logs
for select to authenticated using (exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active
));
